import {
  getDoc,
  getDocs,
  setDoc,
  updateDoc,
  writeBatch,
  onSnapshot,
  getCountFromServer,
  FieldPath,
  Timestamp,
} from 'firebase/firestore';
import { db } from '@/lib/firebase';
import { competitionsCol, competitionDoc, competitionScramblesDoc, competitionPrivateCol } from '@/lib/firebase/collections';
import type { Competition, ScrambleSets } from '@/lib/types';

/** Fixed id of the singleton Daily Practice pseudo-competition (see
 *  ensureDailyPracticeCompetition below). One evergreen doc, not one per
 *  day — per-day uniqueness is enforced on the Result docId instead. */
export const DAILY_PRACTICE_COMPETITION_ID = 'daily-practice';

/** One-time fetch of all competitions. */
export async function getCompetitions(): Promise<Competition[]> {
  const snap = await getDocs(competitionsCol);
  return snap.docs.map((d) => d.data());
}

/** Real-time subscription. Returns unsubscribe function. */
export function subscribeCompetitions(
  onData: (competitions: Competition[]) => void,
  onError?: (err: Error) => void,
): () => void {
  return onSnapshot(
    competitionsCol,
    (snap) => onData(snap.docs.map((d) => d.data())),
    (err) => onError?.(err),
  );
}

/** Total competition count (cheap server-side count). */
export async function getCompetitionCount(): Promise<number> {
  const snap = await getCountFromServer(competitionsCol);
  return snap.data().count;
}

/** Create a new competition. id is generated by the caller. */
export async function addCompetition(
  data: Omit<Competition, 'id'> & { events?: Record<string, boolean> },
): Promise<string> {
  const id = Date.now().toString(36);
  await setDoc(competitionDoc(id), { id, ...data, createdAt: Timestamp.now() } as Competition);
  return id;
}

/** Update an existing competition. */
export async function updateCompetition(
  id: string,
  data: Partial<Omit<Competition, 'id'>>,
): Promise<void> {
  await updateDoc(competitionDoc(id), { ...data, updatedAt: Timestamp.now() });
}

// ── Imported WCA scrambles — competitions/{id}/private/scrambles ─────────────
//
// Admin-only (firestore.rules), and deliberately NOT on the competition
// document: that one is public, so scrambles stored there could be read
// before the round is held. Only admin screens may call these — for anyone
// else the read is refused.

/**
 * Save imported WCA scrambles for a competition. Merges: each event+round
 * block in `sets` replaces that block wholesale (mergeFields, so a group
 * dropped from a re-import really goes away), and every other event/round
 * already stored is left untouched. Creates the document if it's missing.
 */
export async function saveScrambleSets(id: string, sets: ScrambleSets): Promise<void> {
  const blocks = Object.entries(sets).flatMap(([eventId, rounds]) =>
    Object.keys(rounds).map(roundId => new FieldPath('scrambleSets', eventId, roundId)),
  );
  if (blocks.length === 0) return;
  await setDoc(
    competitionScramblesDoc(id),
    { scrambleSets: sets, updatedAt: Timestamp.now() },
    { mergeFields: [...blocks, 'updatedAt'] },
  );
}

/** One-time fetch of a competition's imported scrambles ({} if none). */
export async function getScrambleSets(id: string): Promise<ScrambleSets> {
  const snap = await getDoc(competitionScramblesDoc(id));
  return (snap.data()?.scrambleSets as ScrambleSets | undefined) ?? {};
}

/** Real-time subscription to a competition's imported scrambles ({} if none). */
export function subscribeScrambleSets(
  id: string,
  onData: (sets: ScrambleSets) => void,
  onError?: (err: Error) => void,
): () => void {
  return onSnapshot(
    competitionScramblesDoc(id),
    (snap) => onData((snap.data()?.scrambleSets as ScrambleSets | undefined) ?? {}),
    (err) => onError?.(err),
  );
}

/** Delete a competition permanently, along with everything in its private
 *  subcollection — scrambles, staged imported results (deleting a document
 *  does not delete its subcollections). */
export async function deleteCompetition(id: string): Promise<void> {
  const priv = await getDocs(competitionPrivateCol(id));
  const batch = writeBatch(db);
  priv.docs.forEach((d) => batch.delete(d.ref));
  batch.delete(competitionDoc(id));
  await batch.commit();
}

/** Officially finish a competition: set status='finished' and finishedAt=now. */
export async function finishCompetition(id: string): Promise<void> {
  const now = Timestamp.now();
  await updateDoc(competitionDoc(id), {
    status: 'finished',
    finishedAt: now,
    updatedAt: now,
  });
}

/**
 * Create the Daily Practice pseudo-competition doc if it doesn't exist yet.
 * Idempotent — safe to call on every ResultsEntryTab mount. Status stays
 * 'live' forever so it never enters `useResults`' finished-only feed (kept
 * out of Rankings/Records/public Athlete history), and `isDailyPractice`
 * lets every "list real competitions" call site filter it out.
 */
export async function ensureDailyPracticeCompetition(): Promise<void> {
  const ref = competitionDoc(DAILY_PRACTICE_COMPETITION_ID);
  const snap = await getDoc(ref);
  if (snap.exists()) return;
  await setDoc(ref, {
    id: DAILY_PRACTICE_COMPETITION_ID,
    name: 'Daily Practice',
    status: 'live',
    isDailyPractice: true,
    createdAt: Timestamp.now(),
  } as Competition);
}
